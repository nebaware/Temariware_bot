const dicts: Record<Lang, Dict> = { en, am, or };

/** Translate a key in the given language, with optional {placeholder} interpolation. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = dicts[lang] ?? en;
  let str = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

/** Pick the best language from a header string like "am,en;q=0.8". */
export function pickLang(accept: string | null | undefined): Lang {
  if (!accept) return "en";
  if (accept.startsWith("am")) return "am";
  if (accept.startsWith("or")) return "or";
  return "en";
}
